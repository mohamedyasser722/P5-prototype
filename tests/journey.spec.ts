import { expect, test } from '@playwright/test';

test('guided bank assessment remediates findings, issues and persists an attestation', async ({ page, baseURL }) => {
  const origin = new URL(baseURL!).origin;
  const errors: string[] = [];
  const externalRequests: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('request', (request) => {
    const url = new URL(request.url());
    if (url.protocol.startsWith('http') && url.origin !== origin) externalRequests.push(url.href);
  });
  await page.goto('./');
  await page.getByRole('link', { name: 'Start guided demo' }).click();
  await expect(page.getByLabel('Agent name')).toHaveValue('Customer Support Agent');
  await page.getByRole('button', { name: 'Continue' }).click();
  await page.getByRole('button', { name: 'Continue' }).click();
  await page.getByRole('button', { name: 'Register agent' }).click();

  await page.getByRole('button', { name: 'See How Integration Works' }).click();
  const tour = page.getByRole('dialog');
  await expect(tour).toBeVisible();
  await tour.getByRole('button', { name: 'Pause' }).click();
  await tour.getByRole('button', { name: 'Next scene' }).click();
  await tour.getByRole('button', { name: 'Next scene' }).click();
  await expect(tour.getByText('base_url=', { exact: false })).toBeVisible();
  await tour.getByRole('button', { name: 'Close walkthrough' }).click();
  await page.getByRole('button', { name: 'Simulate Connection Test' }).click();
  await page.getByRole('link', { name: 'Configure assessment' }).click();
  await page.getByRole('button', { name: 'Run assessment' }).click();
  await expect(page.getByText('Running assessment', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('link', { name: 'Open assessment report' }).click();
  await expect(page.getByRole('heading', { name: 'Remediation required' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Issue certificate' })).toBeDisabled();
  await page.getByRole('button', { name: /PRIV-001/ }).click();
  await page.getByRole('link', { name: 'Open safeguards' }).click();
  await page.getByRole('switch', { name: 'Response redaction' }).click();
  await page.getByRole('switch', { name: 'Restricted operation enforcement' }).click();
  await page.getByRole('button', { name: 'Save safeguards' }).click();
  await page.getByRole('link', { name: 'Back to report' }).click();
  await page.getByRole('button', { name: 'Retest Failed Controls' }).click();
  await page.getByRole('link', { name: 'Open assessment report' }).click();
  await expect(page.getByRole('heading', { name: 'Technical controls verified' })).toBeVisible();
  await page.getByRole('button', { name: 'Issue certificate' }).click();
  await expect(page.getByRole('heading', { name: 'Technical Assurance Certificate' })).toBeVisible();
  await expect(page.getByText('Prototype technical assurance attestation. Not an official Egyptian PDPL or government-issued certification.', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Technical Assurance Certificate' })).toBeVisible();
  await page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('link', { name: 'Certificates', exact: true }).click();
  await expect(page.getByText('Customer Support Agent')).toBeVisible();
  expect(errors).toEqual([]);
  expect(externalRequests).toEqual([]);
});

test('mobile registration, reduced-motion walkthrough, limited coverage, and reset', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('./');
  await expect(page.getByRole('heading', { name: 'Workspace overview' })).toBeVisible();
  await page.getByRole('link', { name: 'Register new agent' }).click();
  await page.getByLabel('Agent name').fill('Collections Assistant');
  await page.getByLabel('Agent owner').fill('Samir Adel');
  await page.getByLabel('Use case').fill('Internal collections');
  await page.getByLabel('Description and business purpose').fill('Summarize synthetic collections cases for internal review.');
  await page.getByRole('button', { name: 'Continue' }).click();
  await page.getByLabel('Authorized tools').fill('get_case_summary');
  await page.getByLabel('Restricted operations').fill('send_payment_instruction');
  await page.getByRole('button', { name: 'Continue' }).click();
  await page.getByRole('button', { name: 'Register agent' }).click();
  await page.getByRole('button', { name: 'See How Integration Works' }).click();
  const tour = page.getByRole('dialog');
  await expect(tour.getByRole('button', { name: 'Play', exact: true })).toBeVisible();
  await tour.getByRole('button', { name: 'Next scene' }).click();
  await expect(tour.getByRole('heading', { name: 'P5 Gateway' })).toBeVisible();
  await tour.getByRole('button', { name: 'Next scene' }).click();
  await expect(tour.getByText('base_url=', { exact: false })).toBeVisible();
  expect(await tour.locator('.editor-body').evaluate((editor) => editor.scrollWidth)).toBeLessThanOrEqual(await tour.locator('.editor-body').evaluate((editor) => editor.clientWidth));
  await page.keyboard.press('Escape');
  await expect(tour).toBeHidden();
  await expect(page.getByRole('button', { name: 'See How Integration Works' })).toBeFocused({ timeout: 1500 });
  await page.getByRole('radio', { name: /LLM traffic only/ }).check();
  await page.getByRole('button', { name: 'Simulate Connection Test' }).click();
  await page.getByRole('link', { name: 'Configure assessment' }).click();
  await expect(page.getByText('Tool controls will be unverified with LLM-only coverage.')).toBeVisible();
  await page.getByRole('button', { name: 'Run assessment' }).click();
  await page.getByRole('link', { name: 'Open assessment report' }).click();
  await expect(page.getByRole('button', { name: /SEC-002.*NOT VERIFIED/ })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Issue certificate' })).toBeDisabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.getByRole('button', { name: 'Toggle navigation' }).click();
  await page.getByRole('link', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Reset Demo', exact: true }).click();
  await page.getByRole('button', { name: 'Reset demo data' }).click();
  await expect(page.getByRole('heading', { name: 'Workspace overview' })).toBeVisible();
  await page.reload();
  await expect(page.getByText('Collections Assistant')).toHaveCount(0);
});

test('reset cancels delayed work in another tab', async ({ page, context }) => {
  const connection = await context.newPage();
  await connection.goto('./');
  await connection.getByRole('link', { name: /Treasury Research Copilot Internal research/ }).click();
  await connection.getByRole('link', { name: 'Connect agent' }).click();
  await page.goto('./#/settings');
  await page.getByRole('button', { name: 'Reset Demo', exact: true }).click();
  await connection.getByRole('button', { name: 'Simulate Connection Test' }).click();
  await page.getByRole('button', { name: 'Reset demo data' }).click();
  await expect(page.getByRole('heading', { name: 'Workspace overview' })).toBeVisible();
  await expect(connection.getByRole('alert')).toHaveText('The demo was reset before this action completed.', { timeout: 2500 });
  await expect(connection.getByText('Ready to test')).toBeVisible();
  await connection.reload();
  await expect(connection.getByText('Ready to test')).toBeVisible();
});
